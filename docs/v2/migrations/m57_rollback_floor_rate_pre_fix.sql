-- m57 롤백용: m57 적용 직전(2026-10-13)의 라이브 정의를 pg_get_functiondef로 떠 둔 것.
-- m57은 "3억 이상 / 3억 미만" 두 분기를 하나로 합쳤기 때문에 m57 파일의 숫자만 바꿔서는 되돌릴 수 없다
-- (ELSE 89.745를 90.25로 바꾸면 3~10억 구간까지 90.25가 된다). 되돌릴 때는 이 파일을 그대로 적용한다.
-- 순서: 클라이언트 revert·배포 확인 → m36 재적용(refresh_floorerr_distribution 원복) → SELECT refresh_floorerr_distribution(); → 이 파일.

CREATE OR REPLACE FUNCTION public.get_floor_rate_db(p_at text, p_ep numeric, p_od date)
 RETURNS numeric
 LANGUAGE sql
 IMMUTABLE
AS $function$
SELECT CASE
  WHEN p_at = '조달청' THEN
    CASE WHEN p_od >= '2026-01-30' THEN
      CASE WHEN p_ep >= 5000000000 THEN 87.495 WHEN p_ep >= 1000000000 THEN 88.745 WHEN p_ep >= 300000000 THEN 89.745 ELSE 90.25 END
    ELSE CASE WHEN p_ep >= 5000000000 THEN 85.495 WHEN p_ep >= 1000000000 THEN 86.745 WHEN p_ep >= 300000000 THEN 87.745 ELSE 88.25 END END
  WHEN p_at = '지자체' THEN
    CASE WHEN p_od >= '2025-07-01' THEN
      CASE WHEN p_ep >= 10000000000 THEN 81.995 WHEN p_ep >= 5000000000 THEN 87.495 WHEN p_ep >= 1000000000 THEN 88.745 WHEN p_ep >= 300000000 THEN 89.745 ELSE 90.25 END
    ELSE CASE WHEN p_ep >= 10000000000 THEN 79.995 WHEN p_ep >= 5000000000 THEN 85.495 WHEN p_ep >= 1000000000 THEN 86.745 WHEN p_ep >= 300000000 THEN 87.745 ELSE 88.25 END END
  WHEN p_at = '교육청' THEN
    CASE WHEN p_od >= '2025-07-01' THEN
      CASE WHEN p_ep >= 5000000000 THEN 87.495 WHEN p_ep >= 1000000000 THEN 88.745 WHEN p_ep >= 300000000 THEN 89.745 ELSE 90.25 END
    ELSE CASE WHEN p_ep >= 5000000000 THEN 85.495 WHEN p_ep >= 1000000000 THEN 86.745 WHEN p_ep >= 300000000 THEN 87.745 ELSE 88.25 END END
  WHEN p_at = '한전' THEN
    CASE WHEN p_od >= '2026-02-10' THEN
      CASE WHEN p_ep >= 5000000000 THEN 87.495 WHEN p_ep >= 1000000000 THEN 88.745 WHEN p_ep >= 300000000 THEN 89.745 ELSE 90.25 END
    ELSE CASE WHEN p_ep >= 5000000000 THEN 85.495 WHEN p_ep >= 1000000000 THEN 86.745 WHEN p_ep >= 300000000 THEN 87.745 ELSE 88.25 END END
  WHEN p_at = 'LH' THEN
    CASE WHEN p_od >= '2026-02-01' THEN
      CASE WHEN p_ep >= 5000000000 THEN 87.495 WHEN p_ep >= 1000000000 THEN 88.745 WHEN p_ep >= 300000000 THEN 89.745 ELSE 90.25 END
    ELSE CASE WHEN p_ep >= 5000000000 THEN 85.495 WHEN p_ep >= 1000000000 THEN 86.745 WHEN p_ep >= 300000000 THEN 87.745 ELSE 88.25 END END
  WHEN p_at = '군시설' THEN
    CASE WHEN p_od >= '2026-01-19' THEN
      CASE WHEN p_ep >= 5000000000 THEN 87.495 WHEN p_ep >= 1000000000 THEN 88.745 WHEN p_ep >= 300000000 THEN 89.745 ELSE 90.25 END
    ELSE CASE WHEN p_ep >= 5000000000 THEN 83.495 WHEN p_ep >= 1000000000 THEN 84.745 WHEN p_ep >= 300000000 THEN 85.745 ELSE 86.25 END END
  WHEN p_at = '수자원공사' THEN
    CASE WHEN p_od >= '2026-02-27' THEN
      CASE WHEN p_ep >= 5000000000 THEN 87.495 WHEN p_ep >= 1000000000 THEN 88.745 WHEN p_ep >= 300000000 THEN 89.745 ELSE 90.25 END
    ELSE CASE WHEN p_ep >= 5000000000 THEN 85.495 WHEN p_ep >= 1000000000 THEN 86.745 WHEN p_ep >= 300000000 THEN 87.745 ELSE 88.25 END END
  ELSE
    CASE WHEN p_od >= '2025-07-01' THEN
      CASE WHEN p_ep >= 300000000 THEN 89.745 ELSE 90.25 END
    ELSE CASE WHEN p_ep >= 300000000 THEN 87.745 ELSE 88.25 END END
END;
$function$;

CREATE OR REPLACE FUNCTION public._floor_rate(at text, ba numeric, od date)
 RETURNS numeric
 LANGUAGE sql
 IMMUTABLE
AS $function$
  SELECT CASE
    WHEN at='조달청' AND od >= DATE '2026-01-30' THEN CASE WHEN ba>=5e9 THEN 87.495 WHEN ba>=1e9 THEN 88.745 WHEN ba>=3e8 THEN 89.745 ELSE 90.25 END
    WHEN at='조달청' THEN CASE WHEN ba>=5e9 THEN 85.495 WHEN ba>=1e9 THEN 86.745 WHEN ba>=3e8 THEN 87.745 ELSE 88.25 END
    WHEN at='지자체' AND od >= DATE '2025-07-01' THEN CASE WHEN ba>=1e10 THEN 81.995 WHEN ba>=5e9 THEN 87.495 WHEN ba>=1e9 THEN 88.745 WHEN ba>=3e8 THEN 89.745 ELSE 90.25 END
    WHEN at='지자체' THEN CASE WHEN ba>=1e10 THEN 79.995 WHEN ba>=5e9 THEN 85.495 WHEN ba>=1e9 THEN 86.745 WHEN ba>=3e8 THEN 87.745 ELSE 88.25 END
    WHEN at='교육청' AND od >= DATE '2025-07-01' THEN CASE WHEN ba>=5e9 THEN 87.495 WHEN ba>=1e9 THEN 88.745 WHEN ba>=3e8 THEN 89.745 ELSE 90.25 END
    WHEN at='교육청' THEN CASE WHEN ba>=5e9 THEN 85.495 WHEN ba>=1e9 THEN 86.745 WHEN ba>=3e8 THEN 87.745 ELSE 88.25 END
    WHEN at='한전' AND od >= DATE '2026-02-10' THEN CASE WHEN ba>=5e9 THEN 87.495 WHEN ba>=1e9 THEN 88.745 WHEN ba>=3e8 THEN 89.745 ELSE 90.25 END
    WHEN at='한전' THEN CASE WHEN ba>=5e9 THEN 85.495 WHEN ba>=1e9 THEN 86.745 WHEN ba>=3e8 THEN 87.745 ELSE 88.25 END
    WHEN at='LH' AND od >= DATE '2026-02-01' THEN CASE WHEN ba>=5e9 THEN 87.495 WHEN ba>=1e9 THEN 88.745 WHEN ba>=3e8 THEN 89.745 ELSE 90.25 END
    WHEN at='LH' THEN CASE WHEN ba>=5e9 THEN 85.495 WHEN ba>=1e9 THEN 86.745 WHEN ba>=3e8 THEN 87.745 ELSE 88.25 END
    WHEN at='군시설' AND od >= DATE '2026-01-19' THEN CASE WHEN ba>=5e9 THEN 87.495 WHEN ba>=1e9 THEN 88.745 WHEN ba>=3e8 THEN 89.745 ELSE 90.25 END
    WHEN at='군시설' THEN CASE WHEN ba>=5e9 THEN 83.495 WHEN ba>=1e9 THEN 84.745 WHEN ba>=3e8 THEN 85.745 ELSE 86.25 END
    WHEN at='수자원공사' AND od >= DATE '2026-02-27' THEN CASE WHEN ba>=5e9 THEN 87.495 WHEN ba>=1e9 THEN 88.745 WHEN ba>=3e8 THEN 89.745 ELSE 90.25 END
    WHEN at='수자원공사' THEN CASE WHEN ba>=5e9 THEN 85.495 WHEN ba>=1e9 THEN 86.745 WHEN ba>=3e8 THEN 87.745 ELSE 88.25 END
    ELSE 88.25
  END::NUMERIC
$function$;
